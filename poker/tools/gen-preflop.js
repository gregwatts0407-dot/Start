// Generates js/preflop-data.js: Monte Carlo equity of all 169 starting hands
// against 1 and 3 random opponents. Run: node tools/gen-preflop.js [samples]
const fs = require('fs');
const path = require('path');
const C = require('../js/cards.js');

const SAMPLES = Number(process.argv[2] || 60000);
const rng = C.makeRng(20261122);

function equityVsRandom(hero, opps, samples) {
  const dead = new Set(hero);
  const rest = C.newDeck().filter((c) => !dead.has(c));
  const seven = new Array(7), opp = new Array(7);
  let total = 0;
  for (let i = 0; i < samples; i++) {
    // partial Fisher-Yates for 5 board cards + 2 per opponent
    const need = 5 + 2 * opps;
    for (let k = 0; k < need; k++) {
      const j = k + Math.floor(rng() * (rest.length - k));
      const t = rest[k]; rest[k] = rest[j]; rest[j] = t;
    }
    seven[0] = hero[0]; seven[1] = hero[1];
    for (let k = 0; k < 5; k++) { seven[k + 2] = rest[k]; opp[k + 2] = rest[k]; }
    const hs = C.evaluate(seven, 7);
    let best = 0, ties = 0, lost = false;
    for (let o = 0; o < opps; o++) {
      opp[0] = rest[5 + 2 * o]; opp[1] = rest[6 + 2 * o];
      const s = C.evaluate(opp, 7);
      if (s > hs) { lost = true; break; }
      if (s === hs) ties++;
    }
    if (!lost) total += 1 / (ties + 1);
    void best;
  }
  return total / samples;
}

const classes = C.allClasses();
const out = {};
for (const cls of classes) {
  const combo = C.classToCombos(cls)[0];
  const hu = equityVsRandom(combo, 1, SAMPLES);
  const m3 = equityVsRandom(combo, 3, Math.round(SAMPLES / 2));
  out[cls] = [Math.round(hu * 1000) / 1000, Math.round(m3 * 1000) / 1000];
}

// Rank: blend heads-up equity with 4-way equity (normalised), which rewards
// suited and connected hands the way real opening charts do.
const score = (cls) => out[cls][0] / 0.5 * 0.55 + out[cls][1] / 0.25 * 0.45;
const order = classes.slice().sort((a, b) => score(b) - score(a));

const body = `// Generated by tools/gen-preflop.js — do not edit by hand.
// EQUITY[class] = [equity vs 1 random hand, equity vs 3 random hands]
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.PreflopData = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return {
    EQUITY: ${JSON.stringify(out)},
    ORDER: ${JSON.stringify(order)}
  };
});
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'preflop-data.js'), body);
console.log('top 20:', order.slice(0, 20).join(' '));
console.log('bottom 10:', order.slice(-10).join(' '));
